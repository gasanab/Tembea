// Helper function to get image by category
export const getRwandaImage = (category: keyof typeof RWANDA_IMAGES): string => {
  return RWANDA_IMAGES[category] || RWANDA_IMAGES.fallback1;
};

// Get image for listing type
export const getListingImage = (type: string): string => {
  const imageMap: Record<string, keyof typeof RWANDA_IMAGES> = {
    ACCOMMODATION: "hotel",
    PARKS: "park",
    EVENTS: "event",
    MARKETPLACE: "marketplace",
    RESTAURANTS: "restaurant",
    TOURS: "tour",
    TRANSPORT: "car",
    MUSEUMS: "cultural",
    MEMORIAL_SITES: "cultural",
    GUIDES: "tour",
  };
  
  return RWANDA_IMAGES[imageMap[type] || "fallback1"] || RWANDA_IMAGES.fallback1;
};